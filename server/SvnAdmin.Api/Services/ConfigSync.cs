using System.Security.Cryptography;
using System.Text;
using Dapper;
using Microsoft.Data.Sqlite;
using Microsoft.Extensions.Options;
using SvnAdmin.Data;
using SvnAdmin.Svn;

namespace SvnAdmin.Services;

public sealed record FileStatus(string Path, bool Exists, DateTime? LastWriteUtc, bool ChangedOutsideTool, bool EverWritten);

public sealed record SyncStatus(FileStatus Passwd, FileStatus Authz);

/// <summary>
/// Keeps the Apache passwd and authz files in step with the database.
///
/// Every change goes through <see cref="Mutate{T}"/>, which (under one lock):
///  1. pulls in password changes made outside the tool (e.g. htpasswd or another tool),
///  2. applies the change to the database inside a transaction,
///  3. re-renders both files and writes them atomically, keeping the old copy in ConfigHistoryDir,
///  4. commits only if the files were written.
/// If the authz file was hand-edited since the last write, changes are refused until an admin
/// re-imports it or chooses to overwrite it, so manual edits are never silently lost.
/// </summary>
public sealed class ConfigSync(Db db, IOptions<SvnOptions> options, ILogger<ConfigSync> logger)
{
    private const string AuthzHeader =
        "Generated by SvnAdmin. Do not edit by hand: SvnAdmin will detect the change and\n" +
        "stop saving until an admin re-imports or overwrites this file (System page).";

    private readonly SvnOptions _o = options.Value;
    private readonly SemaphoreSlim _lock = new(1, 1);

    public T Mutate<T>(Actor actor, Func<SqliteConnection, SqliteTransaction, T> change, bool overwriteAuthz = false)
    {
        _lock.Wait();
        try
        {
            using var conn = db.Open();
            using var tx = conn.BeginTransaction();
            ReconcilePasswd(conn, tx);
            var result = change(conn, tx);
            WriteFiles(conn, tx, actor, overwriteAuthz);
            tx.Commit();
            return result;
        }
        finally
        {
            _lock.Release();
        }
    }

    public void Mutate(Actor actor, Action<SqliteConnection, SqliteTransaction> change, bool overwriteAuthz = false) =>
        Mutate<object?>(actor, (c, t) => { change(c, t); return null; }, overwriteAuthz);

    /// <summary>Pull in passwd changes made outside SvnAdmin. Cheap when nothing changed.</summary>
    public void ReconcileIfChanged()
    {
        _lock.Wait();
        try
        {
            using var conn = db.Open();
            using var tx = conn.BeginTransaction();
            ReconcilePasswd(conn, tx);
            tx.Commit();
        }
        finally
        {
            _lock.Release();
        }
    }

    public SyncStatus Status()
    {
        using var conn = db.Open();
        return new SyncStatus(FileState(conn, _o.PasswdFile, "passwd_sha256"), FileState(conn, _o.AuthzFile, "authz_sha256"));
    }

    public string PreviewAuthz()
    {
        using var conn = db.Open();
        return RenderAuthz(conn, null);
    }

    // ------------------------------------------------------------------ import

    /// <summary>First-run import: copies users, groups and rules from the existing files into an empty database.</summary>
    public List<string> ImportInitial(Actor actor)
    {
        _lock.Wait();
        try
        {
            using var conn = db.Open();
            using var tx = conn.BeginTransaction();
            var warnings = new List<string>();
            var now = Clock.Now();

            if (File.Exists(_o.PasswdFile))
            {
                var text = File.ReadAllText(_o.PasswdFile);
                foreach (var e in PasswdFile.Parse(text))
                {
                    conn.Execute("""
                        INSERT OR IGNORE INTO users (username, password_hash, is_enabled, created_at, updated_at)
                        VALUES (@Username, @Hash, 1, @now, @now)
                        """, new { e.Username, e.Hash, now }, tx);
                }
                SetSetting(conn, tx, "passwd_sha256", Sha(text));
                Audit.Write(conn, tx, actor, "import.passwd", _o.PasswdFile, $"{PasswdFile.Parse(text).Count} users");
            }
            else
            {
                warnings.Add($"Passwd file not found: {_o.PasswdFile}");
            }

            if (File.Exists(_o.AuthzFile))
            {
                var text = File.ReadAllText(_o.AuthzFile);
                warnings.AddRange(ImportAuthzInto(conn, tx, text));
                SetSetting(conn, tx, "authz_sha256", Sha(text));
                Audit.Write(conn, tx, actor, "import.authz", _o.AuthzFile, string.Join("\n", warnings));
            }
            else
            {
                warnings.Add($"Authz file not found: {_o.AuthzFile}");
            }

            tx.Commit();
            return warnings;
        }
        finally
        {
            _lock.Release();
        }
    }

    /// <summary>Replace all groups and rules in the database with what is in the authz file now.</summary>
    public List<string> ReimportAuthz(Actor actor)
    {
        _lock.Wait();
        try
        {
            if (!File.Exists(_o.AuthzFile)) throw new NotFoundException($"Authz file not found: {_o.AuthzFile}");
            using var conn = db.Open();
            using var tx = conn.BeginTransaction();
            var text = File.ReadAllText(_o.AuthzFile);
            conn.Execute("DELETE FROM access_rules; DELETE FROM group_group_members; DELETE FROM group_user_members; DELETE FROM groups;", transaction: tx);
            var warnings = ImportAuthzInto(conn, tx, text);
            SetSetting(conn, tx, "authz_sha256", Sha(text));
            Audit.Write(conn, tx, actor, "import.authz", _o.AuthzFile, warnings.Count == 0 ? "Re-imported" : string.Join("\n", warnings));
            tx.Commit();
            return warnings;
        }
        finally
        {
            _lock.Release();
        }
    }

    /// <summary>
    /// Restores SVN access from a config snapshot: password hashes and enabled accounts from its passwd file,
    /// groups and folder rules from its authz file, then rewrites both live files.
    /// Names, emails, two-step sign-in and the audit log are left as they are now.
    /// </summary>
    public List<string> RestoreAccess(Actor actor, string passwdText, string authzText, string snapshotId) =>
        Mutate(actor, (conn, tx) =>
        {
            var now = Clock.Now();
            var entries = PasswdFile.Parse(passwdText).ToDictionary(e => e.Username, e => e.Hash, StringComparer.OrdinalIgnoreCase);
            var users = conn.Query<(long Id, string Username, string PasswordHash, long IsEnabled)>(
                "SELECT id, username, password_hash, is_enabled FROM users", transaction: tx).ToList();
            int restored = 0, disabled = 0, added = 0;

            foreach (var u in users)
            {
                if (entries.TryGetValue(u.Username, out var hash))
                {
                    if (hash != u.PasswordHash || u.IsEnabled != 1)
                    {
                        conn.Execute("UPDATE users SET password_hash = @hash, is_enabled = 1, updated_at = @now WHERE id = @Id",
                            new { hash, now, u.Id }, tx);
                        restored++;
                    }
                }
                else if (u.IsEnabled == 1)
                {
                    conn.Execute("UPDATE users SET is_enabled = 0, updated_at = @now WHERE id = @Id", new { now, u.Id }, tx);
                    disabled++;
                }
            }
            foreach (var (username, hash) in entries)
            {
                if (users.Any(u => u.Username.Equals(username, StringComparison.OrdinalIgnoreCase))) continue;
                conn.Execute("""
                    INSERT INTO users (username, password_hash, is_enabled, created_at, updated_at)
                    VALUES (@username, @hash, 1, @now, @now)
                    """, new { username, hash, now }, tx);
                added++;
            }

            conn.Execute("DELETE FROM access_rules; DELETE FROM group_group_members; DELETE FROM group_user_members; DELETE FROM groups;", transaction: tx);
            var warnings = ImportAuthzInto(conn, tx, authzText);

            // The admin doing the restore must still be an admin afterwards, or nobody may be able to sign in to fix it.
            var adminGroup = _o.AdminGroup;
            if (!Lookups.IsAdmin(conn, tx, actor.Name, adminGroup))
                throw new AppException($"This snapshot doesn't make you a member of '{adminGroup}', so restoring it would lock you out. Nothing was changed.");

            Audit.Write(conn, tx, actor, "backup.restore", snapshotId,
                $"Passwords/accounts: {restored} restored, {disabled} disabled, {added} re-added. Groups and permissions replaced." +
                (warnings.Count > 0 ? "\n" + string.Join("\n", warnings) : ""));
            return warnings;
        }, overwriteAuthz: true);

    private static List<string> ImportAuthzInto(SqliteConnection conn, SqliteTransaction tx, string text)
    {
        var doc = AuthzFile.Parse(text);
        var warnings = new List<string>(doc.Warnings);
        var now = Clock.Now();

        foreach (var g in doc.Groups)
            conn.Execute("INSERT OR IGNORE INTO groups (name, created_at) VALUES (@Name, @now)", new { g.Name, now }, tx);

        foreach (var g in doc.Groups)
        {
            var gid = conn.ExecuteScalar<long>("SELECT id FROM groups WHERE name = @Name", new { g.Name }, tx);
            foreach (var u in g.Users)
            {
                var uid = conn.ExecuteScalar<long?>("SELECT id FROM users WHERE username = @u", new { u }, tx);
                if (uid is null) { warnings.Add($"Group {g.Name}: user \"{u}\" is not in the passwd file; dropped."); continue; }
                conn.Execute("INSERT OR IGNORE INTO group_user_members (group_id, user_id) VALUES (@gid, @uid)", new { gid, uid }, tx);
            }
            foreach (var child in g.Groups)
            {
                var cid = conn.ExecuteScalar<long?>("SELECT id FROM groups WHERE name = @child", new { child }, tx);
                if (cid is null) { warnings.Add($"Group {g.Name}: nested group @{child} is not defined; dropped."); continue; }
                if (cid == gid) { warnings.Add($"Group {g.Name} contains itself; dropped."); continue; }
                conn.Execute("INSERT OR IGNORE INTO group_group_members (group_id, member_group_id) VALUES (@gid, @cid)", new { gid, cid }, tx);
            }
        }

        foreach (var r in doc.Rules)
        {
            if (r.PrincipalType == "group" && !doc.Groups.Any(g => g.Name.Equals(r.PrincipalName, StringComparison.OrdinalIgnoreCase)))
            {
                warnings.Add($"Rule [{r.Repo}{(r.Repo is null ? "" : ":")}{r.Path}] refers to undefined group @{r.PrincipalName}; dropped.");
                continue;
            }
            conn.Execute("""
                INSERT INTO access_rules (repo_name, path, principal_type, principal_name, access)
                VALUES (@Repo, @Path, @PrincipalType, @PrincipalName, @Access)
                ON CONFLICT (repo_name, path, principal_type, principal_name) DO UPDATE SET access = excluded.access
                """, r, tx);
        }
        return warnings;
    }

    // ------------------------------------------------------------------ passwd reconcile

    private void ReconcilePasswd(SqliteConnection conn, SqliteTransaction tx)
    {
        if (!File.Exists(_o.PasswdFile)) return;
        var text = ReadShared(_o.PasswdFile);
        var current = Sha(text);
        var stored = GetSetting(conn, tx, "passwd_sha256");
        if (stored is null || stored == current) return;

        var fileUsers = PasswdFile.Parse(text).ToDictionary(e => e.Username, e => e.Hash, StringComparer.OrdinalIgnoreCase);
        var dbUsers = conn.Query<(long Id, string Username, string PasswordHash, long IsEnabled)>(
            "SELECT id, username, password_hash, is_enabled FROM users", transaction: tx).ToList();
        var now = Clock.Now();
        var actor = new Actor("outside-svnadmin", "");

        foreach (var u in dbUsers)
        {
            var inFile = fileUsers.TryGetValue(u.Username, out var hash);
            if (u.IsEnabled == 1 && inFile && hash != u.PasswordHash)
            {
                conn.Execute("UPDATE users SET password_hash = @hash, password_changed_at = @now, updated_at = @now WHERE id = @Id",
                    new { hash, now, u.Id }, tx);
                Audit.Write(conn, tx, actor, "user.password.external", u.Username, "Password changed in the passwd file (for example by the reset portal).");
            }
            else if (u.IsEnabled == 1 && !inFile)
            {
                conn.Execute("UPDATE users SET is_enabled = 0, updated_at = @now WHERE id = @Id", new { now, u.Id }, tx);
                Audit.Write(conn, tx, actor, "user.disable.external", u.Username, "Removed from the passwd file outside SvnAdmin; disabled here to match.");
            }
            else if (u.IsEnabled == 0 && inFile)
            {
                conn.Execute("UPDATE users SET is_enabled = 1, password_hash = @hash, updated_at = @now WHERE id = @Id", new { hash, now, u.Id }, tx);
                Audit.Write(conn, tx, actor, "user.enable.external", u.Username, "Added back to the passwd file outside SvnAdmin; enabled here to match.");
            }
        }

        foreach (var (username, hash) in fileUsers)
        {
            if (dbUsers.Any(u => u.Username.Equals(username, StringComparison.OrdinalIgnoreCase))) continue;
            conn.Execute("""
                INSERT INTO users (username, password_hash, is_enabled, created_at, updated_at, password_changed_at)
                VALUES (@username, @hash, 1, @now, @now, @now)
                """, new { username, hash, now }, tx);
            Audit.Write(conn, tx, actor, "user.create.external", username, "Found in the passwd file but not in SvnAdmin; imported.");
        }

        SetSetting(conn, tx, "passwd_sha256", current);
        logger.LogInformation("Reconciled passwd file changes made outside SvnAdmin");
    }

    // ------------------------------------------------------------------ rendering & writing

    private void WriteFiles(SqliteConnection conn, SqliteTransaction tx, Actor actor, bool overwriteAuthz)
    {
        var passwd = PasswdFile.Render(conn.Query<PasswdEntry>(
            "SELECT username AS Username, password_hash AS Hash FROM users WHERE is_enabled = 1", transaction: tx));
        var authz = RenderAuthz(conn, tx);

        // Decide everything before touching either file, so a refused change writes nothing.
        var authzPlan = Plan(conn, tx, _o.AuthzFile, authz, "authz_sha256");
        if (authzPlan == WritePlan.Conflict && !overwriteAuthz)
            throw new ConflictException(
                "The authz file was edited outside SvnAdmin since it was last saved, so this change was not applied. " +
                "Open the System page to re-import the file or overwrite it.");
        var passwdPlan = Plan(conn, tx, _o.PasswdFile, passwd, "passwd_sha256");

        if (passwdPlan != WritePlan.Unchanged) AtomicWrite(_o.PasswdFile, passwd);
        if (authzPlan != WritePlan.Unchanged) AtomicWrite(_o.AuthzFile, authz);
        SetSetting(conn, tx, "passwd_sha256", Sha(passwd));
        SetSetting(conn, tx, "authz_sha256", Sha(authz));

        if (authzPlan == WritePlan.Conflict)
            Audit.Write(conn, tx, actor, "authz.overwrite", _o.AuthzFile, "Replaced a hand-edited authz file with SvnAdmin's version.");
    }

    private enum WritePlan { Unchanged, Write, Conflict }

    /// <summary>Conflict means the file on disk is not what SvnAdmin last wrote (someone edited it).</summary>
    private static WritePlan Plan(SqliteConnection conn, SqliteTransaction tx, string path, string content, string key)
    {
        var currentSha = File.Exists(path) ? Sha(ReadShared(path)) : null;
        if (currentSha == Sha(content)) return WritePlan.Unchanged;
        var stored = GetSetting(conn, tx, key);
        return stored is not null && currentSha is not null && stored != currentSha ? WritePlan.Conflict : WritePlan.Write;
    }

    private void AtomicWrite(string path, string content)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        if (File.Exists(path) && !string.IsNullOrWhiteSpace(_o.ConfigHistoryDir))
        {
            Directory.CreateDirectory(_o.ConfigHistoryDir);
            var name = Path.GetFileName(path);
            File.Copy(path, Path.Combine(_o.ConfigHistoryDir, $"{name}.{DateTime.UtcNow:yyyyMMdd-HHmmss-fff}.bak"));
            PruneHistory(name);
        }

        var tmp = path + ".svnadmin-tmp";
        File.WriteAllText(tmp, content, new UTF8Encoding(false));
        // Apache may have the file open for a moment; retry briefly.
        for (var attempt = 1; ; attempt++)
        {
            try
            {
                File.Move(tmp, path, overwrite: true);
                return;
            }
            catch (IOException) when (attempt < 10)
            {
                Thread.Sleep(100 * attempt);
            }
        }
    }

    private void PruneHistory(string fileName)
    {
        var old = new DirectoryInfo(_o.ConfigHistoryDir).GetFiles(fileName + ".*.bak")
            .OrderByDescending(f => f.Name).Skip(Math.Max(1, _o.ConfigHistoryKeep));
        foreach (var f in old)
        {
            try { f.Delete(); } catch (IOException) { /* try again next time */ }
        }
    }

    private static string RenderAuthz(SqliteConnection conn, SqliteTransaction? tx)
    {
        var groups = conn.Query<(long Id, string Name)>("SELECT id, name FROM groups", transaction: tx).ToList();
        var userMembers = conn.Query<(long GroupId, string Username)>(
            "SELECT m.group_id, u.username FROM group_user_members m JOIN users u ON u.id = m.user_id", transaction: tx).ToLookup(x => x.GroupId, x => x.Username);
        var groupMembers = conn.Query<(long GroupId, string Name)>(
            "SELECT m.group_id, g.name FROM group_group_members m JOIN groups g ON g.id = m.member_group_id", transaction: tx).ToLookup(x => x.GroupId, x => x.Name);

        var authzGroups = groups.Select(g => new AuthzGroup(g.Name, userMembers[g.Id].ToList(), groupMembers[g.Id].ToList())).ToList();
        var rules = conn.Query<AuthzRule>(
            "SELECT repo_name AS Repo, path AS Path, principal_type AS PrincipalType, principal_name AS PrincipalName, access AS Access FROM access_rules",
            transaction: tx).ToList();

        Validate(authzGroups, rules);
        return AuthzFile.Render(authzGroups, rules, AuthzHeader);
    }

    /// <summary>mod_authz_svn rejects the whole file (blocking all SVN access) on these errors, so never write one.</summary>
    private static void Validate(List<AuthzGroup> groups, List<AuthzRule> rules)
    {
        var names = groups.Select(g => g.Name).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var r in rules.Where(r => r.PrincipalType == "group" && !names.Contains(r.PrincipalName)))
            throw new AppException($"A permission refers to group @{r.PrincipalName}, which does not exist.");

        var children = groups.ToDictionary(g => g.Name, g => g.Groups, StringComparer.OrdinalIgnoreCase);
        foreach (var g in groups)
        {
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var stack = new Stack<string>(g.Groups);
            while (stack.Count > 0)
            {
                var c = stack.Pop();
                if (c.Equals(g.Name, StringComparison.OrdinalIgnoreCase))
                    throw new AppException($"Group @{g.Name} ends up containing itself through nested groups. Remove one of the nested groups.");
                if (!seen.Add(c)) continue;
                foreach (var gc in children.GetValueOrDefault(c) ?? []) stack.Push(gc);
            }
        }
    }

    // ------------------------------------------------------------------ helpers

    private FileStatus FileState(SqliteConnection conn, string path, string key)
    {
        if (!File.Exists(path)) return new FileStatus(path, false, null, false, GetSetting(conn, null, key) is not null);
        var stored = GetSetting(conn, null, key);
        var current = Sha(ReadShared(path));
        return new FileStatus(path, true, File.GetLastWriteTimeUtc(path), stored is not null && stored != current, stored is not null);
    }

    private static string ReadShared(string path)
    {
        using var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
        using var reader = new StreamReader(fs, Encoding.UTF8);
        return reader.ReadToEnd();
    }

    private static string Sha(string text) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text.Replace("\r\n", "\n"))));

    public static string? GetSetting(SqliteConnection conn, SqliteTransaction? tx, string key) =>
        conn.ExecuteScalar<string?>("SELECT value FROM settings WHERE key = @key", new { key }, tx);

    public static void SetSetting(SqliteConnection conn, SqliteTransaction? tx, string key, string value) =>
        conn.Execute("INSERT INTO settings (key, value) VALUES (@key, @value) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
            new { key, value }, tx);
}
